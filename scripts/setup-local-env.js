#!/usr/bin/env node
/**
 * Generates the env files for the local Docker stack (see docker-compose.yml).
 *
 *   node scripts/setup-local-env.js            # writes .env and Backend_Node_legacy/.env
 *   node scripts/setup-local-env.js --backend-out Backend_Node_legacy/.env.localstack
 *
 * Existing files are never overwritten; pass --force to replace them.
 * All secrets are freshly generated random values — nothing here is shared or reused.
 */
'use strict';

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');

function arg(name, fallback) {
    const i = process.argv.indexOf(name);
    return i !== -1 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
}
const force = process.argv.includes('--force');
const composeOut = path.resolve(ROOT, arg('--compose-out', '.env'));
const backendOut = path.resolve(ROOT, arg('--backend-out', 'Backend_Node_legacy/.env'));

const random = (bytes) => crypto.randomBytes(bytes).toString('hex');

function b64url(input) {
    return Buffer.from(input).toString('base64').replace(/=+$/, '').replace(/\+/g, '-').replace(/\//g, '_');
}

// HS256 JWT in the shape Supabase issues for its API keys; PostgREST switches to `role`.
function signApiKey(role, secret) {
    const header = b64url(JSON.stringify({ alg: 'HS256', typ: 'JWT' }));
    const now = Math.floor(Date.now() / 1000);
    const payload = b64url(JSON.stringify({ iss: 'farmrent-local', role, iat: now, exp: now + 10 * 365 * 24 * 3600 }));
    const sig = crypto.createHmac('sha256', secret).update(`${header}.${payload}`).digest('base64')
        .replace(/=+$/, '').replace(/\+/g, '-').replace(/\//g, '_');
    return `${header}.${payload}.${sig}`;
}

function readExisting(file) {
    if (!fs.existsSync(file)) return {};
    return Object.fromEntries(
        fs.readFileSync(file, 'utf8').split(/\r?\n/)
            .map((l) => l.match(/^([A-Z0-9_]+)=(.*)$/))
            .filter(Boolean)
            .map((m) => [m[1], m[2]]),
    );
}

function writeFile(file, lines) {
    if (fs.existsSync(file) && !force) {
        console.log(`skip   ${path.relative(ROOT, file)} (exists; use --force to replace)`);
        return false;
    }
    fs.writeFileSync(file, lines.join('\n') + '\n', { mode: 0o600 });
    console.log(`wrote  ${path.relative(ROOT, file)}`);
    return true;
}

// Reuse compose secrets if .env already exists so the backend file stays consistent with the running DB.
const prev = readExisting(composeOut);
const POSTGRES_PASSWORD = prev.POSTGRES_PASSWORD || random(16);
const SUPABASE_JWT_SECRET = prev.SUPABASE_JWT_SECRET || random(32);
const SUPABASE_SERVICE_KEY = prev.SUPABASE_SERVICE_KEY || signApiKey('service_role', SUPABASE_JWT_SECRET);
const JWT_SECRET = prev.JWT_SECRET || random(32);
const JWT_REFRESH_SECRET = prev.JWT_REFRESH_SECRET || random(32);
const DB_PORT = prev.DB_PORT || '55432';
const SUPABASE_GATEWAY_PORT = prev.SUPABASE_GATEWAY_PORT || '54321';
const REDIS_PORT = prev.REDIS_PORT || '6380';
const APP_PORT = prev.APP_PORT || '3000';

writeFile(composeOut, [
    '# Generated by scripts/setup-local-env.js — local Docker stack only. Never commit.',
    `POSTGRES_PASSWORD=${POSTGRES_PASSWORD}`,
    `SUPABASE_JWT_SECRET=${SUPABASE_JWT_SECRET}`,
    `SUPABASE_SERVICE_KEY=${SUPABASE_SERVICE_KEY}`,
    `JWT_SECRET=${JWT_SECRET}`,
    `JWT_REFRESH_SECRET=${JWT_REFRESH_SECRET}`,
    `DB_PORT=${DB_PORT}`,
    `SUPABASE_GATEWAY_PORT=${SUPABASE_GATEWAY_PORT}`,
    `REDIS_PORT=${REDIS_PORT}`,
    `APP_PORT=${APP_PORT}`,
]);

writeFile(backendOut, [
    '# Generated by scripts/setup-local-env.js — points the app at the local Docker stack.',
    'NODE_ENV=development',
    `PORT=${APP_PORT}`,
    `APP_URL=http://localhost:${APP_PORT}`,
    `CLIENT_URL=http://localhost:${APP_PORT}`,
    `ALLOWED_ORIGINS=http://localhost:${APP_PORT}`,
    `JWT_SECRET=${JWT_SECRET}`,
    `JWT_REFRESH_SECRET=${JWT_REFRESH_SECRET}`,
    `SUPABASE_URL=http://localhost:${SUPABASE_GATEWAY_PORT}`,
    `SUPABASE_SERVICE_KEY=${SUPABASE_SERVICE_KEY}`,
    `DATABASE_URL=postgres://postgres:${POSTGRES_PASSWORD}@localhost:${DB_PORT}/farmrent`,
    `REDIS_URL=redis://127.0.0.1:${REDIS_PORT}`,
    '# Optional integrations — leave blank for local dev (emails go to /api/dev/emails, OTPs are returned in dev responses).',
    'RAZORPAY_KEY_ID=',
    'RAZORPAY_KEY_SECRET=',
    'RAZORPAY_WEBHOOK_SECRET=',
    'RESEND_API_KEY=',
]);
